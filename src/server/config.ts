import { homedir } from "node:os";
import { join } from "node:path";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { randomBytes } from "node:crypto";
import { DEFAULT_PORT } from "../shared/protocol.ts";
import { DEFAULT_INK, sanitizeInkSettings, type InkSettings } from "../shared/ink.ts";

export interface Config {
  port: number;
  /** Required by clients that connect over the LAN (loopback / USB is trusted). */
  token: string;
  /** Pressure curve; edited from the viewer. */
  ink: InkSettings;
}

export function configDir(): string {
  return (
    process.env.NOTE_TAKER_CONFIG_DIR ??
    join(process.env.XDG_CONFIG_HOME ?? join(homedir(), ".config"), "note-taker")
  );
}

export function dataDir(): string {
  return (
    process.env.NOTE_TAKER_DATA_DIR ??
    join(process.env.XDG_DATA_HOME ?? join(homedir(), ".local", "share"), "note-taker")
  );
}

export function newToken(): string {
  return randomBytes(16).toString("hex");
}

/** Load config.json, creating it (with a fresh token) on first run. */
const configFile = () => join(configDir(), "config.json");

async function readStored(): Promise<Partial<Config>> {
  try {
    return JSON.parse(await readFile(configFile(), "utf8"));
  } catch {
    return {}; // first run or unreadable — regenerated by loadConfig
  }
}

async function writeStored(cfg: Config): Promise<void> {
  await mkdir(configDir(), { recursive: true });
  await writeFile(configFile(), JSON.stringify(cfg, null, 2) + "\n", { mode: 0o600 });
}

export async function loadConfig(): Promise<Config> {
  const stored = await readStored();
  const cfg: Config = {
    port: typeof stored.port === "number" ? stored.port : DEFAULT_PORT,
    token: typeof stored.token === "string" && stored.token.length >= 16 ? stored.token : newToken(),
    ink: sanitizeInkSettings(stored.ink) ?? { ...DEFAULT_INK },
  };

  if (cfg.port !== stored.port || cfg.token !== stored.token || JSON.stringify(cfg.ink) !== JSON.stringify(stored.ink)) {
    await writeStored(cfg);
  }

  const envPort = Number(process.env.NOTE_TAKER_PORT);
  if (Number.isInteger(envPort) && envPort > 0) cfg.port = envPort;
  return cfg;
}

/** Persist new ink settings, keeping everything else in config.json as stored. */
export async function saveInkSettings(ink: InkSettings): Promise<void> {
  const stored = await readStored(); // written by loadConfig at startup
  await writeStored({ ...(stored as Config), ink });
}
